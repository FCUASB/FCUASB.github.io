import {readFile,writeFile} from 'node:fs/promises';
const read=async name=>(await readFile(new URL('../supabase/setup/'+name+'.sql',import.meta.url),'utf8')).replaceAll('\r\n','\n');
const intake=await read('intake-api'),media=await read('media-api');
const columns=intake.split('\n').filter(line=>line.startsWith('alter table archive_private.attachments add column poster_')).map(line=>line.replace('add column ','add column if not exists '));
const functions=[['list_memories',intake],['upload_action',media],['public_media',media]].map(([name,source])=>{
 const start=source.indexOf('create function archive_private.'+name+'(');
 if(start<0)throw Error('Missing function '+name);
 const end=source.indexOf('$$;',start);
 if(end<0)throw Error('Missing function end '+name);
 return source.slice(start,end+3).replace('create function ','create or replace function ');
});
const output=['-- Generated by npm run prepare:video-posters. Upgrade an existing cloud API only.',
 '-- Adds derived JPEG posters; keeps existing RLS, roles, wrappers and receipt expiry unchanged.',
 'begin;',"set local lock_timeout='5s';","set local statement_timeout='30s';",...columns,...functions,'commit;',''].join('\n');
const target=new URL('../supabase/setup/video-posters.sql',import.meta.url);
if(process.argv.includes('--check')){if(await readFile(target,'utf8')!==output)throw Error('Video poster SQL is stale');}
else await writeFile(target,output);
console.log('PASS: 影片封面升級 SQL 與來源一致。');
